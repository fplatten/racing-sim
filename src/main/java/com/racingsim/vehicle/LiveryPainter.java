package com.racingsim.vehicle;

import com.jme3.math.ColorRGBA;
import com.jme3.texture.Image;
import com.jme3.texture.Texture;
import com.jme3.texture.Texture2D;
import com.jme3.texture.plugins.AWTLoader;

import java.awt.BasicStroke;
import java.awt.Color;
import java.awt.Font;
import java.awt.Graphics2D;
import java.awt.RenderingHints;
import java.awt.Shape;
import java.awt.font.GlyphVector;
import java.awt.geom.AffineTransform;
import java.awt.geom.Path2D;
import java.awt.geom.Rectangle2D;
import java.awt.image.BufferedImage;

/**
 * Paints a car's livery texture at runtime. Shapes are defined in car coordinates and mapped
 * through the planar UV islands generated by {@code blender/make_car.py}:
 * <pre>
 *   left side   u = (y - Y_MIN) / L      v = 0.75 + 0.25 * z / Z_MAX
 *   right side  u = (Y_MAX - y) / L      v = 0.50 + 0.25 * z / Z_MAX
 *   top         u = (y - Y_MIN) / L      v = 0.10 + 0.40 * (X_MAX - x) / (2 * X_MAX)
 *   bottom      v in [0, 0.10]
 * </pre>
 * (Blender frame: y = longitudinal, -y forward; z up; x = car's left.)
 */
public final class LiveryPainter {

    private static final float Y_MIN = -2.5f, Y_MAX = 2.6f, Z_MAX = 1.25f, X_MAX = 1.0f;
    private static final float L = Y_MAX - Y_MIN;

    private LiveryPainter() { }

    public static Texture2D paint(Livery livery, int size) {
        BufferedImage img = new BufferedImage(size, size, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = img.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);

        Color primary = awt(livery.primary()), secondary = awt(livery.secondary()), accent = awt(livery.accent());
        Color numberFill = luminance(livery.primary()) < 0.45f ? Color.WHITE : new Color(15, 15, 18);
        Color numberEdge = luminance(livery.primary()) < 0.45f ? new Color(10, 10, 14) : Color.WHITE;

        // whole sheet defaults to primary (bottom island + gutters)
        g.setColor(primary);
        g.fillRect(0, 0, size, size);

        // ---------------- side islands ----------------
        for (int side = 0; side < 2; side++) {
            AffineTransform t = side == 0
                    ? new AffineTransform(size / L, 0, 0, -0.25 * size / Z_MAX, -Y_MIN * size / L, 0.25 * size)
                    : new AffineTransform(-size / L, 0, 0, -0.25 * size / Z_MAX, Y_MAX * size / L, 0.50 * size);
            Rectangle2D island = new Rectangle2D.Double(0, side == 0 ? 0 : 0.25 * size, size, 0.25 * size);
            Graphics2D s = (Graphics2D) g.create();
            s.clip(island);
            s.setColor(secondary);
            s.fill(island);
            AffineTransform base = s.getTransform();
            s.transform(t);
            // lower body in primary
            s.setColor(primary);
            s.fill(poly(-2.7, -0.2, -2.7, 0.170, -1.9, 0.235, -1.2, 0.300, -0.6, 0.330, 0.2, 0.345,
                    1.0, 0.370, 1.8, 0.400, 2.7, 0.420, 2.7, -0.2));
            // airbox / roll hoop
            s.fill(poly(-0.25, 0.64, 0.9, 0.60, 1.35, 0.50, 1.35, 1.3, -0.25, 1.3));
            // pinstripe along the colour break on the nose
            s.setColor(accent);
            s.setStroke(new BasicStroke(0.018f));
            s.draw(poly(-2.45, 0.195, -1.9, 0.255, -1.2, 0.320, -0.6, 0.350, 0.2, 0.365));
            // swoosh: secondary outline + accent core
            s.setColor(secondary);
            s.fill(band(-0.75, 0.15, 1.30, 0.50, 0.11));
            s.setColor(accent);
            s.fill(band(-0.75, 0.15, 1.30, 0.50, 0.065));
            // nose tip
            s.fill(new Rectangle2D.Double(-2.7, -0.2, 0.44, 1.0));
            // front wing endplates
            s.setColor(primary);
            s.fill(new Rectangle2D.Double(-2.48, 0.0, 0.56, 0.28));
            s.setColor(accent);
            s.fill(new Rectangle2D.Double(-2.48, 0.205, 0.56, 0.03));
            // rear wing endplate panel
            s.setColor(primary);
            s.fill(new Rectangle2D.Double(1.94, 0.55, 0.70, 0.64));
            s.setColor(secondary);
            s.fill(new Rectangle2D.Double(1.94, 1.04, 0.70, 0.05));
            s.setColor(accent);
            s.fill(new Rectangle2D.Double(1.94, 1.09, 0.70, 0.05));
            s.setTransform(base);
            // numbers: sidepod + rear wing endplate
            drawNumber(s, livery.number(), t, 0.62, 0.30, 0.20, 0, numberFill, numberEdge);
            drawNumber(s, livery.number(), t, 2.29, 0.885, 0.25, 0, numberFill, numberEdge);
            // sponsor decals: sidepod flank, nose, rear endplate foot, cockpit-side contingency patches
            decal(s, t, sponsor(livery, TITLE), -0.19, 0.330, 0.200, 1.05, 0, true);      // sidepod flank
            decal(s, t, sponsor(livery, NOSE), -1.72, 0.300, 0.125, 0.66, 0, true);       // nose
            decal(s, t, sponsor(livery, ENDPLATE), 2.28, 0.665, 0.130, 0.60, 0, true);    // rear wing endplate
            decal(s, t, sponsor(livery, ENGINE), 0.72, 0.640, 0.105, 0.56, 0, true);      // engine cover
            contingency(s, t, -1.02, 0.455, side == 1);
            s.dispose();
        }

        // ---------------- top island ----------------
        AffineTransform top = new AffineTransform(size / L, 0, 0, 0.2 * size / X_MAX, -Y_MIN * size / L, 0.7 * size);
        Rectangle2D topIsland = new Rectangle2D.Double(0, 0.5 * size, size, 0.4 * size);
        Graphics2D s = (Graphics2D) g.create();
        s.clip(topIsland);
        s.setColor(secondary);
        s.fill(topIsland);
        AffineTransform base = s.getTransform();
        s.transform(top);
        // nose centre band
        Shape noseBand = poly(-2.55, -0.06, -1.6, -0.12, -0.92, -0.17, -0.92, 0.17, -1.6, 0.12, -2.55, 0.06);
        s.setColor(primary);
        s.fill(noseBand);
        s.setColor(accent);
        s.setStroke(new BasicStroke(0.016f));
        s.draw(noseBand);
        s.fill(new Rectangle2D.Double(-2.6, -1, 0.34, 2));               // nose tip
        // airbox + engine cover spine
        s.setColor(primary);
        s.fill(poly(-0.15, -0.13, 1.3, -0.07, 2.1, -0.06, 2.1, 0.06, 1.3, 0.07, -0.15, 0.13));
        // sidepod rear sections + accent slash
        for (int sgn = -1; sgn <= 1; sgn += 2) {
            s.setColor(primary);
            s.fill(poly(0.35, sgn * 0.78, 1.5, sgn * 0.30, 1.5, sgn * 0.85, 0.35, sgn * 0.85));
            s.setColor(accent);
            s.fill(poly(0.20, sgn * 0.78, 0.30, sgn * 0.78, 1.45, sgn * 0.28, 1.35, sgn * 0.28));
        }
        // front wing: primary with secondary/accent stripes on the flap
        s.setColor(primary);
        s.fill(new Rectangle2D.Double(-2.48, 0.12, 0.55, 0.9));
        s.fill(new Rectangle2D.Double(-2.48, -1.02, 0.55, 0.9));
        s.setColor(secondary);
        s.fill(new Rectangle2D.Double(-2.13, -1.02, 0.05, 2.04));
        s.setColor(accent);
        s.fill(new Rectangle2D.Double(-2.08, -1.02, 0.04, 2.04));
        // rear wing
        s.setColor(primary);
        s.fill(new Rectangle2D.Double(2.08, -0.56, 0.52, 1.12));
        s.setColor(secondary);
        s.fill(new Rectangle2D.Double(2.38, -0.56, 0.06, 1.12));
        s.setColor(accent);
        s.fill(new Rectangle2D.Double(2.44, -0.56, 0.05, 1.12));
        s.setTransform(base);
        drawNumber(s, livery.number(), top, -1.86, 0.0, 0.21, Math.PI / 2, numberFill, numberEdge);
        // rear wing: big sponsor across the main plane, readable from behind (up = forward)
        decal(s, top, sponsor(livery, REAR_WING), 2.27, 0.0, 0.25, 0.98, -Math.PI / 2, true);
        // front wing main planes and sidepod tops
        for (int sgn = -1; sgn <= 1; sgn += 2) {
            decal(s, top, sponsor(livery, FRONT_WING), -2.30, sgn * 0.55, 0.17, 0.74, -Math.PI / 2, true);
        }
        s.dispose();
        g.dispose();
        weather(img);

        Image image = new AWTLoader().load(img, false);
        Texture2D tex = new Texture2D(image);
        tex.setMinFilter(Texture.MinFilter.Trilinear);
        tex.setMagFilter(Texture.MagFilter.Bilinear);
        tex.setAnisotropicFilter(8);
        tex.setWrap(Texture.WrapMode.EdgeClamp);
        return tex;
    }

    /** Draws an outlined race number centred at car coordinates (a, b) of the given island transform. */
    private static void drawNumber(Graphics2D g, int number, AffineTransform t, double a, double b,
                                   double heightMetres, double rotation, Color fill, Color edge) {
        double[] p = {a, b};
        t.transform(p, 0, p, 0, 1);
        double pxPerMetre = Math.abs(t.getScaleY());
        float fontPx = (float) (heightMetres * pxPerMetre * 1.35);
        Font font = new Font("Arial", Font.BOLD | Font.ITALIC, 10).deriveFont(fontPx);
        GlyphVector gv = font.createGlyphVector(g.getFontRenderContext(), Integer.toString(number));
        Rectangle2D bounds = gv.getVisualBounds();
        AffineTransform at = new AffineTransform();
        at.translate(p[0], p[1]);
        at.rotate(rotation);
        at.translate(-bounds.getCenterX(), -bounds.getCenterY());
        Shape glyphs = at.createTransformedShape(gv.getOutline());
        g.setStroke(new BasicStroke(Math.max(2f, fontPx * 0.07f), BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND));
        g.setColor(edge);
        g.draw(glyphs);
        g.setColor(fill);
        g.fill(glyphs);
    }

    // ------------------------------------------------------------------ sponsors, decals and wear

    /** Fictional sponsors (SponsorArt brands). */
    private static final String[] SPONSORS = java.util.Arrays.stream(SponsorArt.BRANDS).map(SponsorArt.Brand::name)
            .toArray(String[]::new);

    /**
     * Sponsor spots. Like a real sponsorship package, each car carries six different brands: the
     * title sponsor on the sidepods, then associates on the rear wing, engine cover, endplates,
     * nose and front wing. The offsets are distinct modulo the number of brands, so no brand
     * appears twice on one car.
     */
    private static final int TITLE = 0, REAR_WING = 3, ENGINE = 6, ENDPLATE = 9, NOSE = 12, FRONT_WING = 14;

    /**
     * Brand for a spot on this car. Cars are numbered by their place in the field (Livery.forIndex),
     * and the title sponsor steps through the brands with a stride coprime to their count, so the
     * first 16 cars all have different title sponsors (and therefore different sidepod and engine
     * cover logos); larger fields repeat them, the 17th car taking the 1st car's title, and so on.
     */
    private static String sponsor(Livery livery, int spot) {
        int n = SPONSORS.length;
        return SPONSORS[Math.floorMod(fieldIndex(livery) * 5 + spot, n)];
    }

    private static int fieldIndex(Livery livery) {
        for (int i = 0; i < Livery.MAX_CARS; i++) {
            if (Livery.forIndex(i).number() == livery.number()) return i;
        }
        return Math.floorMod(livery.number(), Livery.MAX_CARS);
    }

    /**
     * A sponsor ad panel ({@link SponsorArt}) centred at car coordinates (a, b) of an island
     * transform: heightMetres tall, maxLength metres long, rotated like text.
     */
    private static void decal(Graphics2D g, AffineTransform t, String sponsor, double a, double b,
                              double heightMetres, double maxLength, double rotation, boolean mascot) {
        double[] p = {a, b};
        t.transform(p, 0, p, 0, 1);
        double pxPerMetre = Math.abs(t.getScaleY());
        SponsorArt.panel(g, SponsorArt.brand(sponsor), p[0], p[1], maxLength * pxPerMetre, heightMetres * pxPerMetre,
                rotation, mascot);
    }

    /** A row of small die-cut contingency stickers (brakes / plugs / gears / seals) on the cockpit side. */
    private static void contingency(Graphics2D g, AffineTransform t, double y0, double z, boolean mirrored) {
        SponsorArt.Brand[] stickers = {
                new SponsorArt.Brand("BRAKES", new Color(250, 250, 250), new Color(220, 20, 30), Color.BLACK, SponsorArt.Mascot.TIRE),
                new SponsorArt.Brand("PLUGS", new Color(255, 215, 0), new Color(15, 15, 15), Color.BLACK, SponsorArt.Mascot.TIRE),
                new SponsorArt.Brand("GEARS", new Color(255, 40, 160), new Color(255, 255, 255), Color.BLACK, SponsorArt.Mascot.TIRE),
                new SponsorArt.Brand("SEALS", new Color(0, 200, 255), new Color(255, 240, 0), Color.BLACK, SponsorArt.Mascot.TIRE)};
        double w = 0.10, h = 0.05;
        double pxPerMetre = Math.abs(t.getScaleY());
        for (int k = 0; k < stickers.length; k++) {
            double[] p = {y0 + w / 2 + k * w, z};
            t.transform(p, 0, p, 0, 1);
            SponsorArt.panel(g, stickers[k], p[0], p[1], w * pxPerMetre, h * pxPerMetre, 0, false);
        }
    }

    /** Blends the shared wear masks ({@link BodyDetail}) into the painted livery. */
    private static void weather(BufferedImage img) {
        BodyDetail d = BodyDetail.get();
        int size = img.getWidth();
        int n = BodyDetail.SIZE;
        int step = n / size;
        int[] row = new int[size];
        for (int y = 0; y < size; y++) {
            img.getRGB(0, y, size, 1, row, 0, size);
            for (int x = 0; x < size; x++) {
                float grime = 0, marbles = 0, chips = 0, soot = 0;
                for (int sy = 0; sy < step; sy++) {                      // box-filter the masks down
                    int base = (y * step + sy) * n + x * step;
                    for (int sx = 0; sx < step; sx++) {
                        grime += d.grime[base + sx];
                        marbles += d.marbles[base + sx];
                        chips += d.chips[base + sx];
                        soot += d.soot[base + sx];
                    }
                }
                float inv = 1f / (step * step);
                grime *= inv; marbles *= inv; chips *= inv; soot *= inv;
                int c = row[x];
                float r = (c >> 16 & 0xFF), gg = (c >> 8 & 0xFF), b = (c & 0xFF);
                // road grime: a brown-grey film
                float k = grime * 0.55f;
                r += (96 - r) * k; gg += (88 - gg) * k; b += (80 - b) * k;
                // soot: dark grey
                k = soot * 0.65f;
                r += (38 - r) * k; gg += (36 - gg) * k; b += (35 - b) * k;
                // stone chips expose dark composite
                k = chips * 0.9f;
                r += (34 - r) * k; gg += (34 - gg) * k; b += (36 - b) * k;
                // rubber marbles
                k = marbles;
                r += (24 - r) * k; gg += (23 - gg) * k; b += (22 - b) * k;
                row[x] = (0xFF << 24) | (Math.round(r) << 16) | (Math.round(gg) << 8) | Math.round(b);
            }
            img.setRGB(0, y, size, 1, row, 0, size);
        }
    }

    private static Shape poly(double... xy) {
        Path2D.Double p = new Path2D.Double();
        p.moveTo(xy[0], xy[1]);
        for (int i = 2; i < xy.length; i += 2) p.lineTo(xy[i], xy[i + 1]);
        if (xy.length > 4 && !(xy[0] == xy[xy.length - 2] && xy[1] == xy[xy.length - 1])) p.closePath();
        return p;
    }

    /** Parallelogram band from (y0, z0) to (y1, z1) with a vertical thickness. */
    private static Shape band(double y0, double z0, double y1, double z1, double thick) {
        double h = thick / 2;
        return poly(y0, z0 - h, y1, z1 - h, y1, z1 + h, y0, z0 + h);
    }

    private static Color awt(ColorRGBA c) {
        return new Color(clamp(c.r), clamp(c.g), clamp(c.b));
    }

    private static float clamp(float v) {
        return Math.max(0f, Math.min(1f, v));
    }

    private static float luminance(ColorRGBA c) {
        return 0.2126f * c.r + 0.7152f * c.g + 0.0722f * c.b;
    }
}
